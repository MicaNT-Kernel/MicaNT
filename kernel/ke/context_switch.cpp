#include "micant/km/core/ke.hpp"

#if defined(MICANT_FREESTANDING) && (defined(_M_X64) || defined(__x86_64__))
extern "C" __attribute__((naked)) bool MicantAmd64SwitchContext(
    micant::ke::KThreadContext*, micant::ke::KThreadContext*) noexcept {
    __asm__ __volatile__(
        "movq %rbx, 24(%rcx)\n"
        "movq %rbp, 32(%rcx)\n"
        "movq %rsi, 40(%rcx)\n"
        "movq %rdi, 48(%rcx)\n"
        "movq %r12, 56(%rcx)\n"
        "movq %r13, 64(%rcx)\n"
        "movq %r14, 72(%rcx)\n"
        "movq %r15, 80(%rcx)\n"
        "leaq 1f(%rip), %rax\n"
        "movq %rax, 0(%rcx)\n"
        "movq %rsp, 8(%rcx)\n"
        "pushfq\n"
        "popq %rax\n"
        "movq %rax, 16(%rcx)\n"
        "stmxcsr 88(%rcx)\n"
        "fnstcw 92(%rcx)\n"
        "movdqu %xmm6, 96(%rcx)\n"
        "movdqu %xmm7, 112(%rcx)\n"
        "movdqu %xmm8, 128(%rcx)\n"
        "movdqu %xmm9, 144(%rcx)\n"
        "movdqu %xmm10, 160(%rcx)\n"
        "movdqu %xmm11, 176(%rcx)\n"
        "movdqu %xmm12, 192(%rcx)\n"
        "movdqu %xmm13, 208(%rcx)\n"
        "movdqu %xmm14, 224(%rcx)\n"
        "movdqu %xmm15, 240(%rcx)\n"
        "movq %rdx, %rax\n"
        "ldmxcsr 88(%rax)\n"
        "fldcw 92(%rax)\n"
        "movdqu 96(%rax), %xmm6\n"
        "movdqu 112(%rax), %xmm7\n"
        "movdqu 128(%rax), %xmm8\n"
        "movdqu 144(%rax), %xmm9\n"
        "movdqu 160(%rax), %xmm10\n"
        "movdqu 176(%rax), %xmm11\n"
        "movdqu 192(%rax), %xmm12\n"
        "movdqu 208(%rax), %xmm13\n"
        "movdqu 224(%rax), %xmm14\n"
        "movdqu 240(%rax), %xmm15\n"
        "movq 24(%rax), %rbx\n"
        "movq 32(%rax), %rbp\n"
        "movq 40(%rax), %rsi\n"
        "movq 48(%rax), %rdi\n"
        "movq 56(%rax), %r12\n"
        "movq 64(%rax), %r13\n"
        "movq 72(%rax), %r14\n"
        "movq 80(%rax), %r15\n"
        "movq 8(%rax), %rsp\n"
        "jmp *0(%rax)\n"
        "1:\n"
        "movl $1, %eax\n"
        "retq\n"
    );
}
#endif
